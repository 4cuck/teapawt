/// Snowflake ID cutoff for RSS GUID format transition. Corresponds to
/// approximately December 14, 2025 UTC.
const GUID_CUTOFF: i64 = 2_000_000_000_000_000_000;

/// A feed opened with proxying on must hand that choice to every page it links,
/// because a reader does not keep the cookie.
fn with_proxy_media(url: &str, proxy: bool) -> String {
   if !proxy {
      return url.to_owned();
   }
   if url.contains('?') {
      format!("{url}&proxyMedia=on")
   } else {
      format!("{url}?proxyMedia=on")
   }
}
fn rss_channel(
   self_url: &str,
   title: &str,
   link: &str,
   description: &str,
   image_block: &str,
   items: &str,
) -> String {
   format!(
      r#"<?xml version="1.0" encoding="UTF-8"?>
<rss xmlns:atom="http://www.w3.org/2005/Atom" xmlns:dc="http://purl.org/dc/elements/1.1/" version="2.0">
  <channel>
    <atom:link href="{self_url}" rel="self" type="application/rss+xml" />
    <title>{title}</title>
    <link>{link}</link>
    <description>{}</description>
    <language>en-us</language>
    <ttl>40</ttl>
{image_block}{items}  </channel>
</rss>"#,
      escape_xml(description),
   )
}

/// Render an RSS feed for a user's timeline with optional pinned tweet.
#[expect(
   clippy::module_name_repetitions,
   reason = "public API name is clear and conventional"
)]
pub fn render_user_rss(
   user: &User,
   tweets: &Tweets,
   config: &Config,
   feed_kind: &str,
   proxy: bool,
) -> String {
   render_user_rss_with_pinned(user, tweets, config, feed_kind, None, proxy)
}

/// Render an RSS feed for a user's timeline with pinned tweet support.
pub fn render_user_rss_with_pinned(
   user: &User,
   tweets: &Tweets,
   config: &Config,
   feed_kind: &str,
   pinned: Option<&Tweet>,
   proxy: bool,
) -> String {
   let url_prefix_owned = crate::utils::host::current_origin(config.url_prefix());
   let url_prefix = url_prefix_owned.as_str();
   let feed_path = match feed_kind {
      "replies" => format!("/{}/with_replies/rss", user.username),
      "reposts" => format!("/{}/reposts/rss", user.username),
      "media" => format!("/{}/media/rss", user.username),
      _ => format!("/{}/rss", user.username),
   };

   let handle = format!("@{}", user.username);
   let title = escape_xml(&format!("{} / {handle}", user.fullname)).replace('\n', " ");
   let description = if user.bio.is_empty() {
      format!("Twitter feed for: {handle}. Generated by {url_prefix}")
   } else {
      let bio = strip_html(&user.bio);
      format!("{bio} | Twitter feed for: {handle}. Generated by {url_prefix}")
   };
   let link = with_proxy_media(&format!("{url_prefix}/{}", user.username), proxy);
   let avatar = formatters::join_base(url_prefix, &get_pic_url(&user.user_pic, config, proxy));
   let image_block = format!(
      "    <image>\n      <title>{title}</title>\n      <link>{link}</link>\n      \
       <url>{avatar}</url>\n      <width>128</width>\n      <height>128</height>\n    \
       </image>\n"
   );

   let items = render_tweet_items_with_pinned(tweets, config, pinned, Some(&user.id), proxy);
   rss_channel(
      &with_proxy_media(&format!("{url_prefix}{feed_path}"), proxy),
      &title,
      &link,
      &description,
      &image_block,
      &items,
   )
}

/// Render an RSS feed for search results.
#[expect(
   clippy::module_name_repetitions,
   reason = "public API name is clear and conventional"
)]
pub fn render_search_rss(query: &str, tweets: &Tweets, config: &Config, proxy: bool) -> String {
   let url_prefix_owned = crate::utils::host::current_origin(config.url_prefix());
   let url_prefix = url_prefix_owned.as_str();
   let esc_name = escape_xml(query);
   let encoded_q = percent_encoding::utf8_percent_encode(query, percent_encoding::NON_ALPHANUMERIC);
   let items = render_tweet_items(tweets, config, proxy);
   let description = format!("Twitter feed for: Search \"{query}\". Generated by {url_prefix}");
   rss_channel(
      &with_proxy_media(&format!("{url_prefix}/search/rss?q={encoded_q}"), proxy),
      &format!("Search results for \"{esc_name}\""),
      &with_proxy_media(&format!("{url_prefix}/search?q={encoded_q}"), proxy),
      &description,
      "",
      &items,
   )
}

/// Render an RSS feed for a Twitter list.
#[expect(
   clippy::module_name_repetitions,
   reason = "public API name is clear and conventional"
)]
pub fn render_list_rss(list: &List, tweets: &Tweets, config: &Config, proxy: bool) -> String {
   let url_prefix_owned = crate::utils::host::current_origin(config.url_prefix());
   let url_prefix = url_prefix_owned.as_str();
   let link = with_proxy_media(&format!("{url_prefix}/i/lists/{}", list.id), proxy);
   let items = render_tweet_items(tweets, config, proxy);
   let title = format!("{} / @{}", escape_xml(&list.name), list.username);
   let description = format!(
      "Twitter feed for: {} by @{}. Generated by {url_prefix}",
      list.name, list.username
   );
   rss_channel(&link, &title, &link, &description, "", &items)
}

/// Render an RSS feed for a conversation thread.
#[expect(
   clippy::module_name_repetitions,
   reason = "public API name is clear and conventional"
)]
pub fn render_thread_rss(
   tweet: &Tweet,
   thread_tweets: &[&Tweet],
   config: &Config,
   proxy: bool,
) -> String {
   let url_prefix_owned = crate::utils::host::current_origin(config.url_prefix());
   let url_prefix = url_prefix_owned.as_str();
   let page = format!("{url_prefix}/{}/status/{}", tweet.user.username, tweet.id);
   let self_url = with_proxy_media(&format!("{page}/rss"), proxy);
   let link = with_proxy_media(&page, proxy);
   let title = escape_xml(&format!(
      "Thread by @{}: {}",
      tweet.user.username,
      strip_html(&tweet.text).chars().take(80).collect::<String>()
   ));
   let description = format!(
      "Thread by @{}. Generated by {url_prefix}",
      tweet.user.username
   );
   let items: String = thread_tweets
      .iter()
      .filter(|tw| tw.available)
      .map(|tw| render_tweet_item(tw, url_prefix, config, proxy))
      .collect();
   rss_channel(&self_url, &title, &link, &description, "", &items)
}

/// Render tweet items for RSS feed.
fn render_tweet_items(tweets: &Tweets, config: &Config, proxy: bool) -> String {
   render_tweet_items_with_pinned(tweets, config, None, None, proxy)
}

/// Render tweet items with optional pinned tweet at top and `userId` filtering.
fn render_tweet_items_with_pinned(
   tweets: &Tweets,
   config: &Config,
   pinned: Option<&Tweet>,
   user_id: Option<&str>,
   proxy: bool,
) -> String {
   let url_prefix_owned = crate::utils::host::current_origin(config.url_prefix());
   let url_prefix = url_prefix_owned.as_str();
   let pinned_id = pinned.map(|tweet| tweet.id);
   let mut seen_links: HashSet<String> = HashSet::new();

   let mut items = Vec::new();

   // Add pinned tweet first if present
   if let Some(pinned_tweet) = pinned
      && pinned_tweet.available
   {
      let link = tweet_link(pinned_tweet);
      if seen_links.insert(link) {
         items.push(render_tweet_item(pinned_tweet, url_prefix, config, proxy));
      }
   }

   // Add regular tweets, skipping pinned if already added and filtering by userId
   for tweet in tweets {
      if !tweet.available || Some(tweet.id) == pinned_id {
         continue;
      }
      // Filter by userId for user timeline feeds
      if user_id.is_some_and(|uid| tweet.user.id != uid) {
         continue;
      }
      let link = tweet_link(tweet.retweet.as_deref().unwrap_or(tweet));
      // Deduplicate by link
      if !seen_links.insert(link) {
         continue;
      }
      items.push(render_tweet_item(tweet, url_prefix, config, proxy));
   }

   items.join("")
}

/// Build title: "Pinned:", "RT @original (by @retweeter):", "R to @user:",
/// then text.
fn get_title(tweet: &Tweet, retweet_username: &str) -> String {
   let mut prefix = String::new();
   if tweet.pinned {
      prefix.push_str("Pinned: ");
   } else if !retweet_username.is_empty() {
      let _ = write!(
         prefix,
         "RT @{} (by @{retweet_username}): ",
         tweet.user.username
      );
   } else if !tweet.reply.is_empty() {
      let _ = write!(prefix, "R to @{}: ", tweet.reply[0]);
   }

   let text = strip_html(&tweet.text);
   if !text.is_empty() {
      const MAX_CHARS: usize = 140;
      let truncated: String = text.chars().take(MAX_CHARS + 1).collect();
      let body = if truncated.chars().count() > MAX_CHARS {
         format!(
            "{}\u{2026}",
            truncated.chars().take(MAX_CHARS).collect::<String>()
         )
      } else {
         truncated
      };
      return format!("{}{}", prefix, escape_xml(&body));
   }

   // Fallback to media type
   if !tweet.photos.is_empty() {
      return format!("{prefix}Image");
   }
   if tweet.video.is_some() {
      return format!("{prefix}Video");
   }
   if !tweet.gifs.is_empty() {
      return format!("{prefix}Gif");
   }

   prefix
}

/// Render the body of a single tweet for RSS.
fn render_rss_tweet(tweet: &Tweet, config: &Config, proxy: bool) -> String {
   let url_prefix_owned = crate::utils::host::current_origin(config.url_prefix());
   let url_prefix = url_prefix_owned.as_str();

   // Use replaceUrls with absolute URLs
   let text = formatters::replace_urls_abs(&escape_tags(&tweet.text), config, url_prefix);
   let mut body = format!("<p>{}</p>", text.replace('\n', "<br>\n"));

   // Photos
   if !tweet.photos.is_empty() {
      for photo in &tweet.photos {
         let pic_url = formatters::join_base(url_prefix, &get_pic_url(&photo.url, config, proxy));
         let alt = crate::views::renderutils::alt_text(
            &photo.alt_text,
            &format!(
               "Image from {}",
               crate::views::renderutils::person_label(&tweet.user)
            ),
         );
         let alt = html_escape(&alt);
         let _ = write!(
            body,
            r#"<img src="{pic_url}" alt="{alt}" style="max-width:250px;" />"#
         );
      }
   }
   if let Some(ref video) = tweet.video {
      // Render videos as linked thumbnails with a "Video" label
      if !video.thumb.is_empty() {
         let thumb_url =
            formatters::join_base(url_prefix, &get_pic_url(&video.thumb, config, proxy));
         let tweet_link = format!("{}{}", url_prefix, tweet_link(tweet));
         let alt = crate::views::renderutils::alt_text(&video.title, "Video");
         let alt = html_escape(&alt);
         let _ = write!(
            body,
            r#"<a href="{tweet_link}">
<br>Video<br>
  <img src="{thumb_url}" alt="{alt}" style="max-width:250px;" />
</a>"#
         );
      }
   }
   for video in &tweet.additional_videos {
      if !video.thumb.is_empty() {
         let thumb_url =
            formatters::join_base(url_prefix, &get_pic_url(&video.thumb, config, proxy));
         let tweet_link = format!("{}{}", url_prefix, tweet_link(tweet));
         let alt = crate::views::renderutils::alt_text(&video.title, "Video");
         let alt = html_escape(&alt);
         let _ = write!(
            body,
            r#"<a href="{tweet_link}">
<br>Video<br>
  <img src="{thumb_url}" alt="{alt}" style="max-width:250px;" />
</a>"#
         );
      }
   }
   for gif in &tweet.gifs {
      // Render GIFs with a <video> element
      let thumb = formatters::join_base(url_prefix, &get_pic_url(&gif.thumb, config, proxy));
      let url = formatters::join_base(url_prefix, &get_video_url(&gif.url, config, proxy));
      let _ = write!(
         body,
         r#"<video poster="{thumb}" autoplay muted loop style="max-width:250px;">
  <source src="{url}" type="video/mp4"></video>"#
      );
   }
   if let Some(ref card) = tweet.card {
      // Card image
      if !card.image.is_empty() {
         let card_url = formatters::join_base(url_prefix, &get_pic_url(&card.image, config, proxy));
         let alt = crate::views::renderutils::alt_text(&card.title, "Link preview");
         let alt = html_escape(&alt);
         let _ = write!(
            body,
            r#"<img src="{card_url}" alt="{alt}" style="max-width:250px;" />"#
         );
      }
   }

   // Community note
   if let Some(ref note) = tweet.note {
      let note_html = community_note_to_html(note);
      let note_text = formatters::replace_urls_abs(&note_html, config, url_prefix);
      let _ = write!(body, "<p><b>Community note:</b> {note_text}</p>");
   }

   // Quote tweet
   if let Some(ref quote) = tweet.quote
      && quote.available
   {
      let quote_link = with_proxy_media(&format!("{}{}", url_prefix, tweet_link(quote)), proxy);
      let quote_body = render_rss_tweet(quote, config, proxy);
      let _ = write!(
         body,
         r#"<hr/>
<blockquote>
<b>{} (@{})</b>
<p>
{quote_body}
</p>
<footer>
— <cite><a href="{quote_link}">{quote_link}</a>
</footer>
</blockquote>"#,
         html_escape(&quote.user.fullname),
         quote.user.username
      );
   }

   body
}

/// Render a single tweet as an RSS item.
fn render_tweet_item(tweet: &Tweet, url_prefix: &str, config: &Config, proxy: bool) -> String {
   // Extract the inner tweet from retweets
   let retweet_username = if tweet.retweet.is_some() {
      tweet.user.username.as_str()
   } else {
      ""
   };
   let display_tweet = tweet.retweet.as_ref().map_or(tweet, |rt| rt.as_ref());

   let pub_date = display_tweet
      .time
      .map(formatters::format_rfc822_time)
      .unwrap_or_default();

   // For retweets, always link to the original tweet using the inner tweet's
   // id and username even when the tweet is age-gated or otherwise unavailable.
   // `get_link` falls back to `/i/status/{id}` when the username is empty, so
   // any non-zero id produces a navigable URL regardless of availability.
   let permalink = if tweet.retweet.is_some() && display_tweet.id != 0 {
      let username = if display_tweet.user.username.is_empty() {
         "i"
      } else {
         &display_tweet.user.username
      };
      format!("{url_prefix}/{username}/status/{}", display_tweet.id)
   } else {
      format!("{url_prefix}{}", tweet_link(display_tweet))
   };
   let link = with_proxy_media(&permalink, proxy);
   let title = formatters::sanitize_xml(&get_title(display_tweet, retweet_username));
   let description = formatters::sanitize_xml(&render_rss_tweet(display_tweet, config, proxy))
      .replace("]]>", "]]]]><![CDATA[>");

   // Use bare tweet IDs for new tweets and URLs for tweets before the cutoff
   let guid = if display_tweet.id >= GUID_CUTOFF {
      format!(
         r#"        <guid isPermaLink="false">{}</guid>"#,
         display_tweet.id
      )
   } else {
      format!("        <guid>{permalink}</guid>")
   };

   format!(
      "      <item>
        <title>{title}</title>
        <dc:creator>@{}</dc:creator>
        <description><![CDATA[{}]]></description>
        <pubDate>{pub_date}</pubDate>
{guid}
        <link>{link}</link>
      </item>
",
      display_tweet.user.username,
      description.trim(),
   )
}

/// Helper to get proxied pic URL path (not full URL).
fn get_pic_url(url: &str, config: &Config, proxy: bool) -> String {
   formatters::get_pic_url(url, config.config.base64_media, proxy)
}

/// Helper to get a signed proxied video URL path (not full URL).
fn get_video_url(url: &str, config: &Config, proxy: bool) -> String {
   formatters::get_vid_url(
      url,
      &config.config.hmac_key,
      config.config.base64_media,
      proxy,
   )
}

/// Escape XML special characters (delegates to shared `html_escape`).
fn escape_xml(input: &str) -> String {
   html_escape(input).into_owned()
}
